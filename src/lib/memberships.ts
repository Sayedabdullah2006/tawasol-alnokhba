export type MembershipPlanId = (typeof MEMBERSHIP_PLANS)[number]['id']

export function getMembershipPlan(planId: string) {
  return MEMBERSHIP_PLANS.find(plan => plan.id === planId) ?? null
}

export function getMembershipPrice(planId: string, months: number) {
  return getMembershipPlan(planId)?.prices.find(price => price.months === months) ?? null
}

export function formatMembershipNumber(value: number | string) {
  return `MBR-${String(value).padStart(5, '0')}`
}

