export function membershipBenefitSelectionLabel(selection: MembershipBenefitSelection) {
  if (selection.type === 'reshare_quote') {
    const action = selection.settings.action === 'quote' ? 'اقتباس' : 'إعادة نشر'
    const delay = selection.settings.delay_days === 2 ? 'بعد يومين' : 'بعد يوم'
    return `${action} ${delay} من نشر المنشور`
  }
  if (selection.type === 'pin') return 'تثبيت المنشور لمدة 6 ساعات'
  return 'حملة ممولة بالتنسيق مع الإدارة'
}
