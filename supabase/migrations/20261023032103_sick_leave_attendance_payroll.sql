create function workforce_private.sick_year_end(p_day date) returns date
language plpgsql stable security invoker set search_path='' as $$
declare current_month record; next_month date; following_month date;
begin
 select * into current_month from workforce_private.sick_hijri_months where first_day<=p_day order by first_day desc limit 1;
 select first_day into next_month from workforce_private.sick_hijri_months where year=current_month.year+1 and month=current_month.month;
 select min(first_day) into following_month from workforce_private.sick_hijri_months where first_day>next_month;
 if next_month is null or following_month is null then raise sqlstate 'PT400' using message='تاريخ الإجازة خارج التقويم المدعوم';end if;
 return least(next_month+(p_day-current_month.first_day),following_month-1);
end $$;

-- Calendar days in medical certificates include weekly rest days; each day counts once.
create function workforce_private.sick_leave_days(p_employee uuid,p_through date,p_pending uuid default null)
returns table(day date,request_id uuid,cycle_start date,cycle_end date,ordinal integer,pay_rate numeric)
language plpgsql stable security invoker set search_path='' as $$
declare row record; anchor date; ending date; used integer:=0;
begin
 for row in select distinct on (d::date) d::date as work_day,q.id from public.wf_employee_requests q
 cross join lateral generate_series((q.starts_at at time zone 'Asia/Riyadh')::date::timestamp,least((q.ends_at at time zone 'Asia/Riyadh')::date,p_through)::timestamp,interval '1 day') d
 where q.employee_id=p_employee and q.kind='leave' and q.leave_type='sick' and q.test_run_id is null
 and (q.status='approved' or q.id=p_pending and q.status='pending') order by d::date,q.id loop
  if anchor is null or row.work_day>=ending then anchor:=row.work_day;ending:=workforce_private.sick_year_end(anchor);used:=0;end if;
  used:=used+1;day:=row.work_day;request_id:=row.id;cycle_start:=anchor;cycle_end:=ending;ordinal:=used;
  pay_rate:=case when used<=30 then 1 when used<=90 then 0.75 else 0 end;return next;
 end loop;
end $$;

create function workforce_private.validate_sick_leave() returns trigger
language plpgsql security invoker set search_path='' as $$
declare first_day date;last_day date;
begin
 if new.kind<>'leave' or new.leave_type<>'sick' then return new;end if;
 if TG_OP='INSERT' and new.status<>'pending' then raise sqlstate 'PT400' using message='قدمي الطلب أولًا لاعتماد المدير';end if;
 if TG_OP='UPDATE' and old.status='approved' and (new.starts_at,new.ends_at,new.attachments,new.status) is distinct from (old.starts_at,old.ends_at,old.attachments,old.status) then raise sqlstate 'PT409' using message='الإجازة المعتمدة محفوظة ولا يمكن تعديلها مباشرة';end if;
 if new.status in ('rejected','cancelled') then return new;end if;
 if not exists(select 1 from jsonb_array_elements(new.attachments) a where a->>'mime_type' in ('application/pdf','image/png','image/jpeg','image/webp') and (a->>'size_bytes')::bigint>0 and a->>'sha256' ~ '^[a-f0-9]{64}$' and a->>'object_path' like 'requests/'||new.id::text||'/%') then
  raise sqlstate 'PT400' using message='أرفقي التقرير الطبي بصيغة PDF أو صورة';end if;
 first_day:=(new.starts_at at time zone 'Asia/Riyadh')::date;last_day:=(new.ends_at at time zone 'Asia/Riyadh')::date;
 if first_day is null or last_day is null or last_day<first_day or last_day-first_day>=120 then raise sqlstate 'PT400' using message='فترة الإجازة المرضية من يوم إلى 120 يومًا';end if;
 if first_day<(select start_date from public.wf_employees where id=new.employee_id) then raise sqlstate 'PT400' using message='الإجازة تسبق تاريخ المباشرة';end if;
 perform workforce_private.sick_year_end(last_day);
 if TG_OP='UPDATE' and new.status='approved' and old.status='pending' then
  perform pg_advisory_xact_lock(hashtextextended(new.employee_id::text,19));
  if exists(select 1 from public.wf_monthly_payroll p where p.employee_id=new.employee_id and p.status='paid' and p.month>=date_trunc('month',first_day)::date) then raise sqlstate 'PT409' using message='توجد مستحقات مصروفة بعد بداية الإجازة؛ راجعي التسوية المالية قبل اعتمادها';end if;
  if exists(select 1 from workforce_private.sick_leave_days(new.employee_id,'2101-12-31',new.id) where ordinal>120) then raise sqlstate 'PT409' using message='تجاوزت الإجازة استحقاق 120 يومًا في السنة المرضية';end if;
 end if;
 return new;
end $$;
create trigger wf_sick_leave_validate before insert or update on public.wf_employee_requests for each row execute function workforce_private.validate_sick_leave();

create function workforce_private.sick_payroll(p_employee uuid,p_month date,p_through date) returns jsonb
language plpgsql stable security invoker set search_path='' as $$
declare row record; monthly numeric; loss numeric:=0;details jsonb:='[]';rate numeric;
begin
 for row in select * from workforce_private.sick_leave_days(p_employee,least(p_through,(p_month+interval '1 month - 1 day')::date)) where day>=p_month loop
  select c.basic_salary+coalesce((select sum((a->>'amount')::numeric) from jsonb_array_elements(c.allowances) a),0) into monthly from public.wf_compensation_versions c
   where c.employee_id=p_employee and c.effective_from<=row.day order by c.effective_from desc,c.revision desc limit 1;
  if not found then raise sqlstate 'PT409' using message='أكملي إعداد راتب الموظفة للفترة أولًا';end if;
  -- Official holidays overlapping sickness receive full holiday pay (implementing regulation Art.24).
  rate:=case when workforce_private.paid_holiday(row.day) is not null then 1 else row.pay_rate end;
  loss:=loss+monthly/30*(1-rate);
  details:=details||jsonb_build_array(jsonb_build_object('day',row.day,'request_id',row.request_id,'cycle_start',row.cycle_start,'cycle_end',row.cycle_end,'ordinal',row.ordinal,'pay_rate',rate,'statutory_rate',row.pay_rate,'amount',round(monthly/30*(1-rate),2)::text));
 end loop;
 return jsonb_build_object('amount',round(loss,2)::text,'days',details);
end $$;
revoke all on function workforce_private.sick_year_end(date),workforce_private.sick_leave_days(uuid,date,uuid),workforce_private.validate_sick_leave(),workforce_private.sick_payroll(uuid,date,date) from public,anon,authenticated;
grant execute on function workforce_private.sick_year_end(date),workforce_private.sick_leave_days(uuid,date,uuid),workforce_private.validate_sick_leave(),workforce_private.sick_payroll(uuid,date,date) to service_role;

create or replace function workforce_private.attendance_payroll(p_employee uuid,p_month date)
returns jsonb language plpgsql stable security invoker set search_path='' as $$
declare tick timestamptz:=workforce_private.work_now(); emp public.wf_employees; d date; first_day date; last_day date;
 workdays integer[]; daily integer; required numeric:=0; credited numeric:=0; missing numeric:=0;
 seconds numeric; gap numeric; fixed numeric; adjustment numeric:=0; day_rate numeric; last_rate numeric;
 covered_days integer:=0; missing_days jsonb:='[]'; term record; activated date; cutoff_on date; leave_day boolean; sick jsonb;
begin
 select * into emp from public.wf_employees where id=p_employee;
 if not found then raise sqlstate 'P0002' using message='الموظفة غير متاحة';end if;
 select p.starts_on,p.cutoff_on into activated,cutoff_on from workforce_private.payroll_attendance_policy p where id;
 select s.workdays,s.daily_minutes into workdays,daily from public.wf_attendance_settings s where s.employee_id=p_employee;
 workdays:=coalesce(workdays,array[0,1,2,3,4,6]);daily:=coalesce(daily,480);
 first_day:=greatest(p_month,emp.start_date,activated);
 last_day:=least((p_month+interval '1 month - 1 day')::date,
   (tick at time zone 'Asia/Riyadh')::date-case when (tick at time zone 'Asia/Riyadh')::date>=cutoff_on and (tick at time zone 'Asia/Riyadh')::time>=time '17:00' then 0 else 1 end);
 for d in select generate_series(first_day::timestamp,last_day::timestamp,interval '1 day')::date loop
  if extract(dow from d)::integer<>all(workdays) then continue;end if;
  if to_char(d,'MM-DD') in ('02-22','09-23') or exists(select 1 from public.wf_paid_calendar_days h where h.day=d) then continue;end if;
  select exists(select 1 from public.wf_employee_requests q where q.employee_id=p_employee and q.test_run_id is null
    and q.kind='leave' and q.leave_type in ('paid','sick') and q.status='approved' and d between (q.starts_at at time zone 'Asia/Riyadh')::date and (q.ends_at at time zone 'Asia/Riyadh')::date) into leave_day;
  if leave_day then continue;end if;
  -- A missing salary version is not a zero-wage working day. Fail closed.
  select c.basic_salary+coalesce((select sum((a->>'amount')::numeric) from jsonb_array_elements(c.allowances) a),0) monthly
   into term from public.wf_compensation_versions c where c.employee_id=p_employee and c.effective_from<=d order by c.effective_from desc,c.revision desc limit 1;
  if not found then raise sqlstate 'PT409' using message='أكملي إعداد راتب الموظفة للفترة أولًا';end if;
  fixed:=term.monthly;day_rate:=fixed/30/8;last_rate:=day_rate;
  with ranges as (
   select greatest(lower(r),d::timestamp at time zone 'Asia/Riyadh') lo,
    least(upper(r),(case when d<cutoff_on then (d+1)::timestamp else d+time '17:00' end) at time zone 'Asia/Riyadh') hi
   from public.wf_attendance_sessions a cross join lateral workforce_private.work_credit_ranges(a,tick) r
   where a.employee_id=p_employee and a.checked_in<((d+1)::timestamp at time zone 'Asia/Riyadh')
    and (a.checked_out>=(d::timestamp at time zone 'Asia/Riyadh') or a.checked_out is null)
   union all
   select greatest(q.starts_at,(d+time '09:00') at time zone 'Asia/Riyadh'),least(q.ends_at,(d+time '17:00') at time zone 'Asia/Riyadh')
   from public.wf_employee_requests q where q.employee_id=p_employee and q.test_run_id is null and q.kind='permission' and q.status='approved'
    and q.starts_at<((d+1)::timestamp at time zone 'Asia/Riyadh') and q.ends_at>(d::timestamp at time zone 'Asia/Riyadh')
  ), merged as(select range_agg(tstzrange(lo,hi,'[)')) rr from ranges where hi>lo)
  select least(daily*60,coalesce(sum(extract(epoch from upper(r)-lower(r))),0)) into seconds from merged cross join lateral unnest(rr) r;
  gap:=greatest(0,daily*60-seconds);required:=required+daily*60;credited:=credited+seconds;missing:=missing+gap;
  adjustment:=adjustment+day_rate*gap/3600;covered_days:=covered_days+1;
  if gap>0 then missing_days:=missing_days||jsonb_build_array(jsonb_build_object('day',d,'required_seconds',daily*60,'credited_seconds',seconds,'missing_seconds',gap,'hourly_rate',round(day_rate,6)::text));end if;
 end loop;
 if last_rate is null then
  select (c.basic_salary+coalesce((select sum((a->>'amount')::numeric) from jsonb_array_elements(c.allowances) a),0))/30/8 into last_rate
   from public.wf_compensation_versions c where c.employee_id=p_employee and c.effective_from<=least((p_month+interval '1 month - 1 day')::date,(tick at time zone 'Asia/Riyadh')::date)
   order by c.effective_from desc,c.revision desc limit 1;
 end if;
 sick:=workforce_private.sick_payroll(p_employee,p_month,(tick at time zone 'Asia/Riyadh')::date);
 adjustment:=adjustment+(sick->>'amount')::numeric;
 return jsonb_build_object('sick_leave',sick,'starts_on',activated,'through',case when last_day>=first_day then last_day else null end,
  'required_seconds',required,'credited_seconds',credited,'missing_seconds',missing,'days',covered_days,
  'hourly_rate',round(last_rate,6)::text,'calculated_amount',round(adjustment,2)::text,'missing_days',missing_days);
end $$;
revoke all on function workforce_private.attendance_payroll(uuid,date) from public,anon,authenticated;
grant execute on function workforce_private.attendance_payroll(uuid,date) to service_role;


create or replace function workforce_private.daily_payroll_accrual(p public.wf_monthly_payroll) returns jsonb
language plpgsql stable security invoker set search_path='' as $$
declare tick timestamptz:=workforce_private.work_now(); today date:=(tick at time zone 'Asia/Riyadh')::date;
 first_day date; last_day date:=(p.month+interval '1 month - 1 day')::date; cutoff date;
 days_total integer; days_elapsed integer; ratio numeric:=0; base numeric:=p.basic_amount+p.allowances_amount;
 gross numeric:=0; insurance numeric:=0; other numeric:=0; settlement numeric:=0; pending numeric:=0;
 credited numeric:=0; daily integer; workdays integer[]; paid_day boolean; term record; hourly numeric;
 detail jsonb; final boolean; day_gap numeric:=0; result numeric; award numeric;
 policy public.wf_employee_insurance_settings; insured_start date; insured_day date; insured_basis numeric:=0; insured_term numeric; insured_denominator numeric;
begin
 select greatest(p.month,e.start_date) into first_day from public.wf_employees e where e.id=p.employee_id;
 select cutoff_on into cutoff from workforce_private.payroll_attendance_policy where id;
 final:=p.status='paid' or today>last_day or today=last_day and today>=cutoff and (tick at time zone 'Asia/Riyadh')::time>=time '17:00';
 select coalesce(sum((d->>'amount')::numeric) filter(where d->>'kind'='insurance'),0),
  coalesce(sum((d->>'amount')::numeric) filter(where d->>'kind'<>'insurance'),0) into insurance,other from jsonb_array_elements(p.deductions) d;
 if final then
  return jsonb_build_object('starts_on',first_day,'through',last_day,'as_of',tick,'closed',true,
   'gross_amount',p.gross_amount::text,'insurance_amount',insurance::text,'other_amount',other::text,
   'attendance_amount',p.attendance_amount::text,'total_amount',p.total_amount::text,'current_credited_seconds',0);
 end if;
 days_total:=greatest(1,last_day-first_day+1);days_elapsed:=greatest(0,least(today,last_day)-first_day+1);
 ratio:=least(1,days_elapsed::numeric/days_total);
 -- The joining-month salary already uses the approved /30 proration. Distribute
 -- that period over its calendar days; a full month always accrues exactly its salary.
 gross:=base*ratio;insurance:=round(insurance*ratio,2);
 -- Calculate the contribution from source wages, not from an already-rounded
 -- monthly contribution. This also respects a later insurance effective date.
 select * into policy from public.wf_employee_insurance_settings where employee_id=p.employee_id;
 if found then
  insured_start:=greatest(first_day,policy.effective_from);
  insured_denominator:=case when insured_start>p.month then 30 else extract(day from last_day) end;
  for insured_day in select generate_series(insured_start::timestamp,least(today,last_day)::timestamp,interval '1 day')::date loop
   select c.basic_salary+coalesce((select sum((a->>'amount')::numeric) from jsonb_array_elements(c.allowances) a where coalesce(a->>'name','') ~* '(سكن|housing)'),0)
    into insured_term from public.wf_compensation_versions c where c.employee_id=p.employee_id and c.effective_from<=insured_day order by c.effective_from desc,c.revision desc limit 1;
   if not found then raise sqlstate 'PT409' using message='أكملي إعداد الراتب الأساسي وبدل السكن أولًا';end if;
   insured_basis:=insured_basis+insured_term;
  end loop;
  insurance:=round(insured_basis/insured_denominator*policy.rate/100,2);
 end if;
 detail:=workforce_private.attendance_payroll(p.employee_id,p.month);
 settlement:=(detail->>'calculated_amount')::numeric;
 if today between first_day and last_day then
  select s.daily_minutes,s.workdays into daily,workdays from public.wf_attendance_settings s where s.employee_id=p.employee_id;
  daily:=coalesce(daily,480);workdays:=coalesce(workdays,array[0,1,2,3,4,6]);
  paid_day:=extract(dow from today)::integer<>all(workdays) or to_char(today,'MM-DD') in ('02-22','09-23')
   or exists(select 1 from public.wf_paid_calendar_days where day=today)
   or exists(select 1 from public.wf_employee_requests q where q.employee_id=p.employee_id and q.test_run_id is null
    and q.kind='leave' and q.status='approved' and q.leave_type in ('paid','sick')
    and today between (q.starts_at at time zone 'Asia/Riyadh')::date and (q.ends_at at time zone 'Asia/Riyadh')::date);
  if not paid_day then
   select (c.basic_salary+coalesce((select sum((a->>'amount')::numeric) from jsonb_array_elements(c.allowances) a),0))/30/8 hourly
    into term from public.wf_compensation_versions c where c.employee_id=p.employee_id and c.effective_from<=today order by c.effective_from desc,c.revision desc limit 1;
   if not found then raise sqlstate 'PT409' using message='أكملي إعداد راتب الموظفة للفترة أولًا';end if;
   hourly:=term.hourly;
   with ranges as (
    select greatest(lower(r),today::timestamp at time zone 'Asia/Riyadh') lo,
     least(upper(r),tick,(case when today<cutoff then (today+1)::timestamp else today+time '17:00' end) at time zone 'Asia/Riyadh') hi
    from public.wf_attendance_sessions a cross join lateral workforce_private.work_credit_ranges(a,tick) r
    where a.employee_id=p.employee_id and a.checked_in<((today+1)::timestamp at time zone 'Asia/Riyadh')
     and (a.checked_out>=today::timestamp at time zone 'Asia/Riyadh' or a.checked_out is null)
    union all
    select greatest(q.starts_at,(today+time '09:00') at time zone 'Asia/Riyadh'),least(q.ends_at,(today+time '17:00') at time zone 'Asia/Riyadh',tick)
    from public.wf_employee_requests q where q.employee_id=p.employee_id and q.test_run_id is null and q.kind='permission' and q.status='approved'
     and q.starts_at<((today+1)::timestamp at time zone 'Asia/Riyadh') and q.ends_at>today::timestamp at time zone 'Asia/Riyadh'
   ), merged as(select range_agg(tstzrange(lo,hi,'[)')) rr from ranges where hi>lo)
   select least(daily*60,coalesce(sum(extract(epoch from upper(r)-lower(r))),0)) into credited from merged cross join lateral unnest(rr) r;
   day_gap:=greatest(0,daily*60-credited)*hourly/3600;
   if (detail->>'through')::date=today then
    -- At 17:00 the monthly settlement includes today. Keep it exactly once.
    settlement:=greatest(0,settlement-round(day_gap,2));
   end if;
   pending:=least(base/days_total,day_gap);
  end if;
 end if;
 -- Recorded incentives are earned when entered; future salary is never included.
 award:=case when days_elapsed>0 then greatest(0,p.gross_amount-base) else 0 end;
 gross:=round(greatest(0,gross-pending)+award,2);settlement:=round(least(settlement,greatest(0,gross-insurance-other)),2);
 result:=greatest(0,gross-insurance-other-settlement)+p.reimbursement_amount;
 return jsonb_build_object('starts_on',first_day,'through',case when days_elapsed>0 then least(today,last_day) else null end,
  'as_of',tick,'closed',false,'gross_amount',gross::text,'insurance_amount',insurance::text,'other_amount',other::text,
  'attendance_amount',settlement::text,'total_amount',result::text,'current_credited_seconds',credited);
end $$;
revoke all on function workforce_private.daily_payroll_accrual(public.wf_monthly_payroll) from public,anon,authenticated;
grant execute on function workforce_private.daily_payroll_accrual(public.wf_monthly_payroll) to service_role;


