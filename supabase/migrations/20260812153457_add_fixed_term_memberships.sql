CREATE OR REPLACE FUNCTION public.activate_membership(
  p_membership_id uuid, p_provider text, p_provider_payment_id text, p_provider_response jsonb DEFAULT NULL
) RETURNS public.memberships
LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE
  v_membership public.memberships;
  v_price public.membership_plan_prices;
  v_wallet public.membership_credit_wallets;
  v_start timestamptz := now();
  v_benefit record;
BEGIN
  SELECT * INTO v_membership FROM public.memberships WHERE id = p_membership_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'membership_not_found'; END IF;
  IF v_membership.status = 'active' AND v_membership.payment_status = 'paid' THEN RETURN v_membership; END IF;
  IF v_membership.status NOT IN ('pending_payment', 'payment_review') THEN RAISE EXCEPTION 'membership_not_payable'; END IF;
  SELECT * INTO v_price FROM public.membership_plan_prices WHERE id = v_membership.plan_price_id AND active;
  IF NOT FOUND THEN RAISE EXCEPTION 'membership_plan_unavailable'; END IF;

  UPDATE public.memberships SET status='active', payment_status='paid', payment_provider=p_provider,
    moyasar_payment_id=CASE WHEN p_provider='moyasar' THEN p_provider_payment_id ELSE moyasar_payment_id END,
    tamara_order_id=CASE WHEN p_provider='tamara' THEN p_provider_payment_id ELSE tamara_order_id END,
    paid_at=COALESCE(paid_at,now()), starts_at=COALESCE(starts_at,v_start),
    ends_at=COALESCE(ends_at,v_start + make_interval(months => duration_months)), updated_at=now()
  WHERE id=p_membership_id RETURNING * INTO v_membership;

  INSERT INTO public.membership_credit_wallets (membership_id,total_credits,expires_at)
  VALUES (v_membership.id,v_price.included_credits,v_membership.ends_at)
  ON CONFLICT (membership_id) DO NOTHING RETURNING * INTO v_wallet;
  IF v_wallet.id IS NULL THEN SELECT * INTO v_wallet FROM public.membership_credit_wallets WHERE membership_id=v_membership.id; END IF;
  INSERT INTO public.membership_credit_ledger (membership_id,wallet_id,transaction_type,credits,note,idempotency_key)
  VALUES (v_membership.id,v_wallet.id,'grant',v_price.included_credits,'إضافة رصيد العضوية الكامل','grant:'||v_membership.id::text)
  ON CONFLICT (idempotency_key) DO NOTHING;

  FOR v_benefit IN SELECT key, value::integer AS units FROM jsonb_each_text(v_price.benefit_entitlements) LOOP
    IF v_benefit.units > 0 THEN
      INSERT INTO public.membership_benefit_wallets (membership_id,benefit_type,total_units,unit_budget,expires_at)
      VALUES (v_membership.id,v_benefit.key,v_benefit.units,
        CASE WHEN v_benefit.key='paid_campaign' THEN v_price.ad_budget_per_30_days ELSE 0 END,v_membership.ends_at)
      ON CONFLICT (membership_id,benefit_type) DO NOTHING;
    END IF;
  END LOOP;

  INSERT INTO public.membership_payments (membership_id,provider,provider_payment_id,amount,status,provider_response,paid_at)
  VALUES (v_membership.id,p_provider,p_provider_payment_id,v_membership.total_amount,'paid',p_provider_response,now())
  ON CONFLICT (provider,provider_payment_id) WHERE provider_payment_id IS NOT NULL
  DO UPDATE SET status='paid',provider_response=EXCLUDED.provider_response,paid_at=COALESCE(public.membership_payments.paid_at,EXCLUDED.paid_at),updated_at=now();
  INSERT INTO public.membership_agreements (membership_id,version,terms_snapshot,accepted_at,accepted_ip,accepted_user_agent)
  VALUES (v_membership.id,v_membership.terms_version,v_membership.terms_snapshot,v_membership.terms_accepted_at,v_membership.acceptance_ip,v_membership.acceptance_user_agent)
  ON CONFLICT (membership_id,version) DO NOTHING;
  RETURN v_membership;
END; $$;

CREATE OR REPLACE FUNCTION public.reserve_membership_credit(
  p_membership_id uuid, p_request_id uuid, p_credits integer DEFAULT 1
) RETURNS public.membership_credit_wallets
LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE
  v_membership public.memberships; v_plan public.membership_plans;
  v_wallet public.membership_credit_wallets; v_active_requests integer;
BEGIN
  IF p_credits <= 0 THEN RAISE EXCEPTION 'invalid_credit_amount'; END IF;
  SELECT * INTO v_membership FROM public.memberships WHERE id=p_membership_id FOR UPDATE;
  IF NOT FOUND OR v_membership.status<>'active' OR now()<v_membership.starts_at OR now()>=v_membership.ends_at THEN RAISE EXCEPTION 'membership_inactive'; END IF;
  SELECT * INTO v_plan FROM public.membership_plans WHERE id=v_membership.plan_id AND active;
  SELECT * INTO v_wallet FROM public.membership_credit_wallets WHERE membership_id=v_membership.id FOR UPDATE;
  IF NOT FOUND OR v_wallet.expires_at<=now() THEN RAISE EXCEPTION 'membership_wallet_unavailable'; END IF;
  SELECT count(*) INTO v_active_requests FROM public.publish_requests WHERE membership_id=v_membership.id AND id<>p_request_id
    AND status NOT IN ('completed','rejected','client_rejected','cancelled','auto_closed','refunded');
  IF v_active_requests>=v_plan.concurrent_request_limit THEN RAISE EXCEPTION 'membership_concurrent_limit'; END IF;
  IF v_wallet.total_credits-v_wallet.reserved_credits-v_wallet.used_credits<p_credits THEN RAISE EXCEPTION 'membership_insufficient_credits'; END IF;
  UPDATE public.membership_credit_wallets SET reserved_credits=reserved_credits+p_credits,updated_at=now() WHERE id=v_wallet.id RETURNING * INTO v_wallet;
  UPDATE public.publish_requests SET billing_source='membership',membership_id=v_membership.id,membership_wallet_id=v_wallet.id,
    membership_credits=p_credits,membership_credit_status='reserved',updated_at=now() WHERE id=p_request_id;
  INSERT INTO public.membership_credit_ledger (membership_id,wallet_id,request_id,transaction_type,credits,note,idempotency_key)
  VALUES (v_membership.id,v_wallet.id,p_request_id,'reserve',-p_credits,'حجز رصيد لطلب جديد','reserve:'||p_request_id::text)
  ON CONFLICT (idempotency_key) DO NOTHING;
  RETURN v_wallet;
END; $$;

CREATE OR REPLACE FUNCTION public.consume_membership_credit(p_request_id uuid) RETURNS void
LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE v_request public.publish_requests;
BEGIN
  SELECT * INTO v_request FROM public.publish_requests WHERE id=p_request_id FOR UPDATE;
  IF NOT FOUND OR v_request.billing_source<>'membership' OR v_request.membership_credit_status='consumed' THEN RETURN; END IF;
  IF v_request.membership_credit_status<>'reserved' THEN RAISE EXCEPTION 'membership_credit_not_reserved'; END IF;
  UPDATE public.membership_credit_wallets SET reserved_credits=reserved_credits-v_request.membership_credits,
    used_credits=used_credits+v_request.membership_credits,updated_at=now() WHERE id=v_request.membership_wallet_id;
  UPDATE public.publish_requests SET membership_credit_status='consumed',updated_at=now() WHERE id=p_request_id;
  INSERT INTO public.membership_credit_ledger (membership_id,wallet_id,request_id,transaction_type,credits,note,idempotency_key)
  VALUES (v_request.membership_id,v_request.membership_wallet_id,p_request_id,'consume',-v_request.membership_credits,'بدء التنفيذ واستهلاك الرصيد','consume:'||p_request_id::text)
  ON CONFLICT (idempotency_key) DO NOTHING;
END; $$;

CREATE OR REPLACE FUNCTION public.release_membership_credit(p_request_id uuid,p_note text DEFAULT NULL) RETURNS void
LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE v_request public.publish_requests;
BEGIN
  SELECT * INTO v_request FROM public.publish_requests WHERE id=p_request_id FOR UPDATE;
  IF NOT FOUND OR v_request.billing_source<>'membership' OR v_request.membership_credit_status<>'reserved' THEN RETURN; END IF;
  UPDATE public.membership_credit_wallets SET reserved_credits=reserved_credits-v_request.membership_credits,updated_at=now() WHERE id=v_request.membership_wallet_id;
  UPDATE public.publish_requests SET membership_credit_status='released',updated_at=now() WHERE id=p_request_id;
  INSERT INTO public.membership_credit_ledger (membership_id,wallet_id,request_id,transaction_type,credits,note,idempotency_key)
  VALUES (v_request.membership_id,v_request.membership_wallet_id,p_request_id,'release',v_request.membership_credits,COALESCE(p_note,'إعادة الرصيد المحجوز'),'release:'||p_request_id::text)
  ON CONFLICT (idempotency_key) DO NOTHING;
END; $$;

CREATE OR REPLACE FUNCTION public.reserve_membership_benefits(p_request_id uuid,p_benefits jsonb) RETURNS void
LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE v_request public.publish_requests; v_type text; v_wallet public.membership_benefit_wallets;
BEGIN
  SELECT * INTO v_request FROM public.publish_requests WHERE id=p_request_id AND billing_source='membership' FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'membership_request_not_found'; END IF;
  FOR v_type IN SELECT jsonb_array_elements_text(COALESCE(p_benefits,'[]'::jsonb)) LOOP
    IF v_type NOT IN ('reshare_quote','pin','paid_campaign') THEN RAISE EXCEPTION 'invalid_membership_benefit'; END IF;
    SELECT * INTO v_wallet FROM public.membership_benefit_wallets
      WHERE membership_id=v_request.membership_id AND benefit_type=v_type AND expires_at>now() FOR UPDATE;
    IF NOT FOUND OR v_wallet.total_units-v_wallet.reserved_units-v_wallet.used_units<1 THEN RAISE EXCEPTION 'membership_benefit_unavailable:%',v_type; END IF;
    UPDATE public.membership_benefit_wallets SET reserved_units=reserved_units+1,updated_at=now() WHERE id=v_wallet.id;
    INSERT INTO public.membership_request_benefits (membership_id,request_id,wallet_id,benefit_type)
      VALUES (v_request.membership_id,p_request_id,v_wallet.id,v_type) ON CONFLICT (request_id,benefit_type) DO NOTHING;
    INSERT INTO public.membership_benefit_ledger (membership_id,wallet_id,request_id,transaction_type,units,note,idempotency_key)
      VALUES (v_request.membership_id,v_wallet.id,p_request_id,'reserve',-1,'حجز ميزة للطلب','benefit-reserve:'||p_request_id::text||':'||v_type)
      ON CONFLICT (idempotency_key) DO NOTHING;
  END LOOP;
END; $$;

CREATE OR REPLACE FUNCTION public.consume_membership_benefits(p_request_id uuid) RETURNS void
LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE v_item public.membership_request_benefits;
BEGIN
  FOR v_item IN SELECT * FROM public.membership_request_benefits WHERE request_id=p_request_id AND status='reserved' FOR UPDATE LOOP
    UPDATE public.membership_benefit_wallets SET reserved_units=reserved_units-v_item.units,used_units=used_units+v_item.units,updated_at=now() WHERE id=v_item.wallet_id;
    UPDATE public.membership_request_benefits SET status='consumed',updated_at=now() WHERE id=v_item.id;
    INSERT INTO public.membership_benefit_ledger (membership_id,wallet_id,request_id,transaction_type,units,note,idempotency_key)
      VALUES (v_item.membership_id,v_item.wallet_id,p_request_id,'consume',-v_item.units,'بدء تنفيذ ميزة الطلب','benefit-consume:'||p_request_id::text||':'||v_item.benefit_type)
      ON CONFLICT (idempotency_key) DO NOTHING;
  END LOOP;
END; $$;

CREATE OR REPLACE FUNCTION public.release_membership_benefits(p_request_id uuid,p_note text DEFAULT NULL) RETURNS void
LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE v_item public.membership_request_benefits;
BEGIN
  FOR v_item IN SELECT * FROM public.membership_request_benefits WHERE request_id=p_request_id AND status='reserved' FOR UPDATE LOOP
    UPDATE public.membership_benefit_wallets SET reserved_units=reserved_units-v_item.units,updated_at=now() WHERE id=v_item.wallet_id;
    UPDATE public.membership_request_benefits SET status='released',updated_at=now() WHERE id=v_item.id;
    INSERT INTO public.membership_benefit_ledger (membership_id,wallet_id,request_id,transaction_type,units,note,idempotency_key)
      VALUES (v_item.membership_id,v_item.wallet_id,p_request_id,'release',v_item.units,COALESCE(p_note,'إعادة رصيد الميزة'),'benefit-release:'||p_request_id::text||':'||v_item.benefit_type)
      ON CONFLICT (idempotency_key) DO NOTHING;
  END LOOP;
END; $$;

