-- Fixed-term memberships run alongside direct publish requests.
CREATE TABLE public.membership_plans (
  id text PRIMARY KEY,
  name_ar text NOT NULL,
  description_ar text NOT NULL,
  concurrent_request_limit integer NOT NULL DEFAULT 1 CHECK (concurrent_request_limit > 0),
  revision_rounds integer NOT NULL DEFAULT 1 CHECK (revision_rounds >= 0),
  extra_request_discount_pct numeric(5,2) NOT NULL DEFAULT 0 CHECK (extra_request_discount_pct BETWEEN 0 AND 100),
  features jsonb NOT NULL DEFAULT '[]'::jsonb,
  accent text NOT NULL DEFAULT 'silver',
  sort_order integer NOT NULL DEFAULT 0,
  active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.membership_plan_prices (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  plan_id text NOT NULL REFERENCES public.membership_plans(id) ON DELETE CASCADE,
  duration_months integer NOT NULL CHECK (duration_months IN (3, 6, 12)),
  included_credits integer NOT NULL CHECK (included_credits > 0),
  benefit_entitlements jsonb NOT NULL DEFAULT '{}'::jsonb,
  ad_budget_per_30_days numeric(12,2) NOT NULL DEFAULT 0 CHECK (ad_budget_per_30_days >= 0),
  subtotal numeric(12,2) NOT NULL CHECK (subtotal > 0),
  vat_amount numeric(12,2) NOT NULL CHECK (vat_amount >= 0),
  total_amount numeric(12,2) NOT NULL CHECK (total_amount > 0),
  active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (plan_id, duration_months)
);

CREATE TABLE public.memberships (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  membership_number bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  user_id uuid NOT NULL REFERENCES public.profiles(id) ON DELETE RESTRICT,
  plan_id text NOT NULL REFERENCES public.membership_plans(id),
  plan_price_id uuid NOT NULL REFERENCES public.membership_plan_prices(id),
  duration_months integer NOT NULL CHECK (duration_months IN (3, 6, 12)),
  status text NOT NULL DEFAULT 'pending_payment' CHECK (status IN (
    'pending_payment', 'payment_review', 'active', 'paused', 'expired', 'cancelled', 'refunded'
  )),
  client_name text NOT NULL,
  client_email text NOT NULL,
  client_phone text,
  subtotal numeric(12,2) NOT NULL,
  vat_amount numeric(12,2) NOT NULL,
  total_amount numeric(12,2) NOT NULL,
  starts_at timestamptz,
  ends_at timestamptz,
  payment_provider text CHECK (payment_provider IN ('moyasar', 'tamara', 'bank_transfer')),
  payment_status text NOT NULL DEFAULT 'pending' CHECK (payment_status IN (
    'pending', 'payment_review', 'paid', 'failed', 'refunded'
  )),
  moyasar_payment_id text,
  tamara_order_id text,
  receipt_url text,
  paid_at timestamptz,
  terms_version text NOT NULL,
  terms_snapshot text NOT NULL,
  terms_accepted_at timestamptz NOT NULL,
  privacy_accepted_at timestamptz NOT NULL,
  acceptance_ip text,
  acceptance_user_agent text,
  contract_path text,
  contract_generated_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.membership_credit_wallets (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  membership_id uuid NOT NULL UNIQUE REFERENCES public.memberships(id) ON DELETE CASCADE,
  total_credits integer NOT NULL CHECK (total_credits >= 0),
  reserved_credits integer NOT NULL DEFAULT 0 CHECK (reserved_credits >= 0),
  used_credits integer NOT NULL DEFAULT 0 CHECK (used_credits >= 0),
  expires_at timestamptz NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CHECK (reserved_credits + used_credits <= total_credits)
);

CREATE TABLE public.membership_benefit_wallets (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  membership_id uuid NOT NULL REFERENCES public.memberships(id) ON DELETE CASCADE,
  benefit_type text NOT NULL CHECK (benefit_type IN ('reshare_quote', 'pin', 'paid_campaign')),
  total_units integer NOT NULL CHECK (total_units >= 0),
  reserved_units integer NOT NULL DEFAULT 0 CHECK (reserved_units >= 0),
  used_units integer NOT NULL DEFAULT 0 CHECK (used_units >= 0),
  unit_budget numeric(12,2) NOT NULL DEFAULT 0 CHECK (unit_budget >= 0),
  expires_at timestamptz NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (membership_id, benefit_type),
  CHECK (reserved_units + used_units <= total_units)
);

CREATE TABLE public.membership_credit_ledger (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  membership_id uuid NOT NULL REFERENCES public.memberships(id) ON DELETE CASCADE,
  wallet_id uuid REFERENCES public.membership_credit_wallets(id) ON DELETE SET NULL,
  request_id uuid REFERENCES public.publish_requests(id) ON DELETE SET NULL,
  transaction_type text NOT NULL CHECK (transaction_type IN ('grant', 'reserve', 'consume', 'release', 'adjustment', 'expire')),
  credits integer NOT NULL CHECK (credits <> 0),
  note text,
  created_by uuid REFERENCES public.profiles(id) ON DELETE SET NULL,
  idempotency_key text UNIQUE,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.membership_benefit_ledger (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  membership_id uuid NOT NULL REFERENCES public.memberships(id) ON DELETE CASCADE,
  wallet_id uuid REFERENCES public.membership_benefit_wallets(id) ON DELETE SET NULL,
  request_id uuid REFERENCES public.publish_requests(id) ON DELETE SET NULL,
  transaction_type text NOT NULL CHECK (transaction_type IN ('grant', 'reserve', 'consume', 'release', 'adjustment', 'expire')),
